import { readdir, readFile, writeFile, mkdir } from "node:fs/promises";
import { createHash } from "node:crypto";
import { resolve } from "node:path";
import { execFileSync } from "node:child_process";

// All imported records are drafts. The preview flag is deliberately separate from publication.
const root = resolve(import.meta.dirname, "..");
const manifestPath = process.argv.includes("--manifest")
  ? process.argv[process.argv.indexOf("--manifest") + 1]
  : resolve(root, "data/r2-manifest.json");
const remoteManifest = JSON.parse(await readFile(manifestPath, "utf8"));
const remote = new Map(
  (
    remoteManifest?.images ||
    remoteManifest?.artworks ||
    remoteManifest ||
    []
  ).map((item) => [item.source || item.sourcePath || item.source_path, item]),
);
const artworks = [];
const seen = new Map();
const sourceMap = [];
await mkdir(resolve(root, "data"), { recursive: true });
const featured = [
  "g01-gal33",
  "g01-gal25",
  "g01-gal36",
  "g01-gal1",
  "g01-gal15",
  "g01-gal35",
];
for (const group of ["g01", "g02", "g03"]) {
  const folder = resolve(root, "gallery/archive", group);
  const files = (await readdir(folder))
    .filter((file) => /^gal\d+\.jpe?g$/i.test(file))
    .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }));
  for (const file of files) {
    const source = `gallery/archive/${group}/${file}`;
    const bytes = await readFile(resolve(root, source));
    const digest = createHash("sha256").update(bytes).digest("hex");
    if (seen.has(digest)) {
      sourceMap.push({ source, artworkId: seen.get(digest), duplicate: true });
      continue;
    }
    const stem = `${group}-${file.replace(/\.jpe?g$/i, "")}`;
    const id = `SS-${stem.toUpperCase()}`;
    const number = file.match(/\d+/)[0];
    const uploaded = remote.get(source);
    const web = uploaded?.derivatives?.find((item) => item.role === "web");
    if (!web)
      throw new Error(
        `R2 manifest is missing ${source}; upload it before importing.`,
      );
    if (uploaded.source_sha256 !== digest)
      throw new Error(`Source changed since R2 upload: ${source}`);
    const info = { width: web.width, height: web.height };
    const key = web.object_key;
    const url = web.url;
    const artwork = {
      id,
      slug: stem,
      title: `Archive work ${group.slice(1)}.${number.padStart(3, "0")}`,
      description: "",
      price: null,
      currency: "INR",
      priceMode: "request",
      medium: "",
      width: null,
      height: null,
      unit: "cm",
      year: null,
      availability: "available",
      seriesId: null,
      sortOrder: artworks.length + 10,
      featured: featured.includes(stem),
      images: [
        {
          key,
          url,
          alt: `Painting from Sharmila Sharma’s archive, reference ${id}`,
          width: info.width,
          height: info.height,
        },
      ],
      version: 1,
    };
    if (featured.includes(stem)) artwork.sortOrder = featured.indexOf(stem);
    artworks.push(artwork);
    seen.set(digest, id);
    sourceMap.push({ source, artworkId: id, sha256: digest, duplicate: false });
  }
}
artworks.sort((a, b) => a.sortOrder - b.sortOrder);
const quote = (value) => `'${String(value).replace(/'/g, "''")}'`;
const sql = [
  "-- Generated by scripts/import-legacy.mjs. No artwork is published by this import.",
];
for (const a of artworks) {
  sql.push(
    `INSERT OR IGNORE INTO artworks (id, slug, draft_json, version) VALUES (${quote(a.id)},${quote(a.slug)},${quote(JSON.stringify(a))},1);`,
  );
  sql.push(
    `INSERT OR IGNORE INTO artwork_revisions (id,artwork_id,action,artwork_json,version) VALUES (${quote("import-" + a.id)},${quote(a.id)},'create',${quote(JSON.stringify(a))},1);`,
  );
}
sql.push(
  "INSERT OR IGNORE INTO series (id,slug,name,description,sort_order) VALUES ('school','school','School','',0),('puppet','puppet','Puppet','',1);",
);
await writeFile(
  resolve(root, "data/legacy-preview.json"),
  JSON.stringify(artworks, null, 2) + "\n",
);
await writeFile(
  resolve(root, "data/legacy-sources.json"),
  JSON.stringify(sourceMap, null, 2) + "\n",
);
await writeFile(resolve(root, "data/legacy-drafts.sql"), sql.join("\n") + "\n");
console.log(
  `${artworks.length} draft paintings prepared; ${sourceMap.filter((x) => x.duplicate).length} byte-identical duplicates skipped. No paintings published.`,
);
if (process.argv.includes("--apply"))
  execFileSync(
    "npx",
    [
      "wrangler",
      "d1",
      "execute",
      "DB",
      "--local",
      "--file",
      "data/legacy-drafts.sql",
    ],
    { cwd: root, stdio: "inherit" },
  );
